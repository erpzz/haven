"""Synthetic identity-graph tenants, questions, and gold answers for the query-writing evaluation.

The question: does a small model that *writes a graph query* (code computes the answer)
beat a model that *reasons over the graph in text*? Gold answers come from plain Python
graph traversal in this file, not from Cypher, so the query engine and the gold are
independent. `ORACLE_CYPHER` holds hand-written reference queries; the tests require them
to agree with the gold on every question, which validates the engine, the schema and the
gold together.

This is a development suite generated by the same lane that builds the system. The
independent held-out set, built on public BloodHound/EntraOps sample data, is specified
and held by the assurance lane (issue #117) and is not in this repository.
"""
from __future__ import annotations

import collections
import random

ROLES = [  # (name, tier)
    ("Global Administrator", 0), ("Privileged Role Administrator", 0), ("User Access Administrator", 0),
    ("Application Administrator", 1), ("Exchange Administrator", 1), ("Helpdesk Administrator", 2),
    ("Reports Reader", 2), ("Security Reader", 2)]
FIRST = ["ava", "ben", "chloe", "dev", "elif", "farah", "gus", "hana", "ivo", "jun", "kemi", "lars", "mona",
         "nils", "omar", "pia", "quinn", "rui", "sana", "tomas", "uma", "vik", "wen", "xavi", "yara", "zane"]
TEAMS = ["finance", "platform", "secops", "hr", "sales", "legal", "infra", "data", "support", "exec"]
SCHEMA = """Graph schema (Kùzu / openCypher):
Node tables:
  User(id STRING PRIMARY KEY, enabled BOOLEAN)
  Grp(id STRING PRIMARY KEY)                      -- security groups
  ServicePrincipal(id STRING PRIMARY KEY)
  Role(name STRING PRIMARY KEY, tier INT64)        -- tier 0 = most privileged
Relationship tables:
  MEMBER_OF   (User -> Grp), (Grp -> Grp)          -- group membership; groups can be nested
  HAS_ROLE    (User -> Role), (Grp -> Role), (ServicePrincipal -> Role)
              properties: mode STRING ('active' or 'eligible'), scope STRING ('/' = tenant-wide)
  OWNS        (User -> ServicePrincipal)           -- an owner can act as the service principal
Membership is transitive: a member of a nested group inherits the outer group's roles."""


def make_tenant(seed: str, n_users=28, n_groups=12, n_sps=5) -> dict:
    r = random.Random(seed)
    users = [{"id": f"{n}.{r.choice(TEAMS)}{i}", "enabled": r.random() > 0.15}
             for i, n in enumerate(r.sample(FIRST * 2, n_users))]
    groups = [f"grp-{t}-{i}" for i, t in enumerate(r.choices(TEAMS, k=n_groups))]
    sps = [f"sp-{t}-app{i}" for i, t in enumerate(r.choices(TEAMS, k=n_sps))]
    member = set()
    for u in users:  # each user in 1-2 groups, a few in none
        for g in r.sample(groups, r.choice([0, 1, 1, 2])):
            member.add((u["id"], g))
    order = groups[:]
    r.shuffle(order)
    for i, g in enumerate(order[1:], 1):  # nesting only "downward" in a random order: acyclic
        if r.random() < 0.55:
            member.add((g, r.choice(order[:i])))
    has_role = set()
    for g in r.sample(groups, 5):
        role = r.choice(ROLES)[0]
        has_role.add((g, role, r.choice(["active", "active", "eligible"]), "/"))
    for u in r.sample(users, 6):
        role = r.choice(ROLES)[0]
        has_role.add((u["id"], role, r.choice(["active", "eligible"]), r.choice(["/", "/", "/subscriptions/finance"])))
    for sp in r.sample(sps, 3):
        has_role.add((sp, r.choice(ROLES[:5])[0], "active", "/"))
    owns = {(r.choice(users)["id"], sp) for sp in sps if r.random() < 0.8}
    return {"seed": seed, "users": users, "groups": groups, "sps": sps, "member": sorted(member),
            "has_role": sorted(has_role), "owns": sorted(owns)}


# ------------------------------------------------------------------ gold (plain Python)
def _containers(t, principal):
    """All groups a principal belongs to, directly or through nesting, with hop counts."""
    out_edges = collections.defaultdict(list)
    for a, g in t["member"]:
        out_edges[a].append(g)
    dist, frontier = {}, [(principal, 0)]
    while frontier:
        node, d = frontier.pop(0)
        for g in out_edges[node]:
            if g not in dist:
                dist[g] = d + 1
                frontier.append((g, d + 1))
    return dist


def _roles_of(t, principal, mode=None, tenant_wide=True):
    """Roles held directly or via any containing group -> min hops to the role edge."""
    holders = {principal: 0, **_containers(t, principal)}
    best = {}
    for p, role, m, scope in t["has_role"]:
        if p in holders and (mode is None or m == mode) and (not tenant_wide or scope == "/"):
            best[role] = min(best.get(role, 99), holders[p] + 1)
    return best


def tier(role):
    return dict(ROLES)[role]


def questions(t: dict, rng: random.Random) -> list[dict]:
    uid = [u["id"] for u in t["users"]]
    enabled = {u["id"]: u["enabled"] for u in t["users"]}
    role_names = sorted({h[1] for h in t["has_role"]}) or [ROLES[0][0]]
    qs = []

    def add(family, text, answer, kind, **params):
        qs.append({"id": f"{t['seed']}-{family}-{len(qs)}", "family": family, "question": text,
                   "answer": answer, "kind": kind, "params": params})

    def pick_role(fn):
        # prefer roles with a non-empty answer (about 80%), so "nobody" is not a safe default
        live = [ro for ro in role_names if fn(ro)]
        return rng.choice(live) if live and rng.random() < 0.8 else rng.choice(role_names)

    role = pick_role(lambda ro: any(h[1] == ro and h[2] == "active" for h in t["has_role"]))
    add("direct_holders", f"Which principals (users, groups or service principals) have a direct ACTIVE assignment "
        f"of the role '{role}', at any scope? Return their ids.",
        sorted({p for p, ro, m, s in t["has_role"] if ro == role and m == "active"}), "set", role=role)
    if rng.random() < 0.5 and any(_containers(t, x) for x in uid):  # balanced true/false
        u = rng.choice([x for x in uid if _containers(t, x)])
        g = rng.choice(sorted(_containers(t, u)))
    else:
        u = rng.choice(uid)
        g = rng.choice([x for x in t["groups"] if x not in _containers(t, u)] or t["groups"])
    add("transitive_member", f"Is user '{u}' a member of group '{g}', directly or through nested groups? Answer true or false.",
        g in _containers(t, u), "bool", user=u, group=g)
    role = pick_role(lambda ro: any(ro in _roles_of(t, x, "active") for x in uid))
    add("effective_holders", f"Which USERS hold the role '{role}' with an ACTIVE tenant-wide (scope '/') assignment, "
        f"either directly or through any (possibly nested) group membership? Return user ids.",
        sorted(x for x in uid if role in _roles_of(t, x, "active")), "set", role=role)
    role = pick_role(lambda ro: any(ro in _roles_of(t, x, "eligible") and ro not in _roles_of(t, x, "active") for x in uid))
    add("eligible_only", f"Which USERS are ELIGIBLE for '{role}' tenant-wide (directly or via nested groups) but do "
        f"NOT hold it as an active tenant-wide assignment by any path? Return user ids.",
        sorted(x for x in uid if role in _roles_of(t, x, "eligible") and role not in _roles_of(t, x, "active")),
        "set", role=role)
    add("stale_privileged", "Which DISABLED users still hold any tier-0 role through an ACTIVE tenant-wide assignment, "
        "directly or through nested groups? Return user ids.",
        sorted(x for x in uid if not enabled[x] and any(tier(ro) == 0 for ro in _roles_of(t, x, "active"))), "set")
    sp_t0 = {p for p, ro, m, s in t["has_role"] if p in t["sps"] and m == "active" and s == "/" and tier(ro) == 0}
    add("owner_escalation", "Which users OWN a service principal that holds an ACTIVE tenant-wide tier-0 role? "
        "Return user ids.", sorted({o for o, sp in t["owns"] if sp in sp_t0}), "set")
    g = rng.choice(t["groups"])
    add("transitive_count", f"How many distinct USERS are members of group '{g}', directly or through nested groups? "
        "Return a number.", sum(1 for x in uid if g in _containers(t, x)), "int", group=g)
    return qs


# ------------------------------------------------------------------ reference queries (validated by tests)
ORACLE_CYPHER = {
    "direct_holders": "MATCH (p)-[h:HAS_ROLE]->(r:Role {{name: '{role}'}}) WHERE h.mode = 'active' RETURN DISTINCT p.id",
    "transitive_member": "MATCH (u:User {{id: '{user}'}}) OPTIONAL MATCH (u)-[:MEMBER_OF*1..10]->(g:Grp {{id: '{group}'}}) "
                         "RETURN count(g) > 0",
    "effective_holders": "MATCH (u:User)-[:MEMBER_OF*0..10]->(x)-[h:HAS_ROLE]->(r:Role {{name: '{role}'}}) "
                         "WHERE h.mode = 'active' AND h.scope = '/' RETURN DISTINCT u.id",
    "eligible_only": "MATCH (u:User)-[:MEMBER_OF*0..10]->(x)-[h:HAS_ROLE]->(r:Role {{name: '{role}'}}) "
                     "WHERE h.mode = 'eligible' AND h.scope = '/' WITH DISTINCT u "
                     "OPTIONAL MATCH (u)-[:MEMBER_OF*0..10]->(y)-[a:HAS_ROLE]->(:Role {{name: '{role}'}}) "
                     "WHERE a.mode = 'active' AND a.scope = '/' WITH u, count(a) AS act WHERE act = 0 RETURN u.id",
    "stale_privileged": "MATCH (u:User)-[:MEMBER_OF*0..10]->(x)-[h:HAS_ROLE]->(r:Role) "
                        "WHERE u.enabled = false AND h.mode = 'active' AND h.scope = '/' AND r.tier = 0 RETURN DISTINCT u.id",
    "owner_escalation": "MATCH (u:User)-[:OWNS]->(s:ServicePrincipal)-[h:HAS_ROLE]->(r:Role) "
                        "WHERE h.mode = 'active' AND h.scope = '/' AND r.tier = 0 RETURN DISTINCT u.id",
    "transitive_count": "MATCH (u:User)-[:MEMBER_OF*1..10]->(g:Grp {{id: '{group}'}}) RETURN count(DISTINCT u)",
}


# ------------------------------------------------------------------ engine
def load_kuzu(t: dict, path: str):
    import kuzu
    db = kuzu.Database(path)
    c = kuzu.Connection(db)
    for stmt in ("CREATE NODE TABLE User(id STRING, enabled BOOLEAN, PRIMARY KEY(id))",
                 "CREATE NODE TABLE Grp(id STRING, PRIMARY KEY(id))",
                 "CREATE NODE TABLE ServicePrincipal(id STRING, PRIMARY KEY(id))",
                 "CREATE NODE TABLE Role(name STRING, tier INT64, PRIMARY KEY(name))",
                 "CREATE REL TABLE MEMBER_OF(FROM User TO Grp, FROM Grp TO Grp)",
                 "CREATE REL TABLE HAS_ROLE(FROM User TO Role, FROM Grp TO Role, FROM ServicePrincipal TO Role, "
                 "mode STRING, scope STRING)",
                 "CREATE REL TABLE OWNS(FROM User TO ServicePrincipal)"):
        c.execute(stmt)
    for u in t["users"]:
        c.execute("CREATE (:User {id: $id, enabled: $e})", {"id": u["id"], "e": u["enabled"]})
    for g in t["groups"]:
        c.execute("CREATE (:Grp {id: $id})", {"id": g})
    for s in t["sps"]:
        c.execute("CREATE (:ServicePrincipal {id: $id})", {"id": s})
    for name, tr in ROLES:
        c.execute("CREATE (:Role {name: $n, tier: $t})", {"n": name, "t": tr})
    label = {**{u["id"]: "User" for u in t["users"]}, **{g: "Grp" for g in t["groups"]},
             **{s: "ServicePrincipal" for s in t["sps"]}}
    for a, g in t["member"]:
        c.execute(f"MATCH (a:{label[a]} {{id: $a}}), (g:Grp {{id: $g}}) CREATE (a)-[:MEMBER_OF]->(g)", {"a": a, "g": g})
    for p, role, m, scope in t["has_role"]:
        c.execute(f"MATCH (p:{label[p]} {{id: $p}}), (r:Role {{name: $r}}) "
                  "CREATE (p)-[:HAS_ROLE {mode: $m, scope: $s}]->(r)", {"p": p, "r": role, "m": m, "s": scope})
    for o, s in t["owns"]:
        c.execute("MATCH (u:User {id: $u}), (s:ServicePrincipal {id: $s}) CREATE (u)-[:OWNS]->(s)", {"u": o, "s": s})
    return db, c


def execute(conn, cypher: str, timeout_ms: int = 5000):
    """Execute model- or rule-written Cypher read-only; return raw rows."""
    lowered = cypher.casefold()
    if any(w in lowered for w in ("create ", "delete ", "set ", "merge ", "drop ", "copy ", "load ", "install ", "attach ")):
        raise ValueError("write or admin statement refused")
    conn.set_query_timeout(timeout_ms)
    return conn.execute(cypher).get_all()


def infer_type(rows) -> str:
    """Answer type from the result's own shape (used only when an arm declares none)."""
    if len(rows) == 1 and rows[0] and len(rows[0]) == 1:
        v = rows[0][0]
        if isinstance(v, bool):
            return "bool"
        if isinstance(v, int):
            return "int"
    return "set"


def normalize(rows, kind: str):
    """Rows -> answer value for the type the ARM declared (never the gold's type)."""
    if kind == "set":
        return sorted({str(r[0]) for r in rows if r and r[0] not in (None, "")})
    if kind == "bool":
        # a real boolean is taken as given; otherwise "the query returned a row" means yes
        if rows and rows[0] and isinstance(rows[0][0], bool):
            return rows[0][0]
        return bool([r for r in rows if r and r[0] not in (None, "", 0)])
    if kind == "int":
        return int(rows[0][0]) if rows and rows[0] and isinstance(rows[0][0], (int, float)) else None
    raise ValueError(kind)


def run_query(conn, cypher: str, kind: str, timeout_ms: int = 5000):
    """Reference path (oracle check only): execute and normalize to a known type."""
    return normalize(execute(conn, cypher, timeout_ms), kind)


def graph_as_text(t: dict) -> str:
    """The whole tenant as plain lines, for the arm where the model reasons without a query engine."""
    lines = ["Users (id, enabled): " + "; ".join(f"{u['id']} ({'enabled' if u['enabled'] else 'DISABLED'})" for u in t["users"]),
             "Groups: " + ", ".join(t["groups"]), "Service principals: " + ", ".join(t["sps"]),
             "Roles (name: tier): " + "; ".join(f"{n}: {tr}" for n, tr in ROLES), "Memberships (member -> group):"]
    lines += [f"  {a} -> {g}" for a, g in t["member"]]
    lines += ["Role assignments (principal -> role [mode, scope]):"]
    lines += [f"  {p} -> {r} [{m}, {s}]" for p, r, m, s in t["has_role"]]
    lines += ["Ownership (user -> service principal):"] + [f"  {o} -> {s}" for o, s in t["owns"]]
    return "\n".join(lines)


def make_suite(seed: str, n_tenants: int = 8):
    rng = random.Random(seed)
    suite = []
    for i in range(n_tenants):
        t = make_tenant(f"{seed}-t{i}")
        suite.append({"tenant": t, "questions": questions(t, rng)})
    return suite
